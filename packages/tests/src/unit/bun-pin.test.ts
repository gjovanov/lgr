import { describe, it, expect } from 'bun:test'
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { join, resolve } from 'node:path'

/**
 * One Bun, everywhere it is chosen: `.bun-version`.
 *
 * Production, CI and this machine ran three different Bun releases (1.3.10, 1.3.10 and 1.4.1),
 * and three bugs on 2026-10-23 lived only in the one production and CI ran. The version is now
 * written once and every other place is checked against it:
 *   - the Dockerfile's base image, by tag (and pinned by digest beside it);
 *   - every workflow's setup-bun step, which must read the file, not carry its own copy;
 *   - `package.json#packageManager`.
 * And `bun.lock` is committed, generated by that Bun, and installed `--frozen-lockfile`.
 */

const ROOT = resolve(import.meta.dir, '../../../..')
const read = (rel: string) => readFileSync(join(ROOT, rel), 'utf8')
const PIN = read('.bun-version').trim()

describe('Bun is pinned in one place', () => {
  it('.bun-version names one exact release', () => {
    expect(PIN).toMatch(/^\d+\.\d+\.\d+$/)
  })

  it('the Dockerfile builds on that release, pinned by digest, from the lockfile', () => {
    const docker = read('Dockerfile')
    expect(docker).toMatch(new RegExp(`^FROM oven/bun:${PIN.replace(/\./g, '\\.')}-slim@sha256:[0-9a-f]{64} AS base$`, 'm'))
    expect(docker).toMatch(/^RUN bun install --frozen-lockfile$/m)
  })

  it('every workflow reads the file instead of naming a version', () => {
    const dir = join(ROOT, '.github/workflows')
    for (const f of readdirSync(dir).filter(n => n.endsWith('.yml'))) {
      const text = readFileSync(join(dir, f), 'utf8')
      if (!text.includes('oven-sh/setup-bun')) continue
      expect({ f, inline: /bun-version:\s/.test(text) }).toEqual({ f, inline: false })
      expect({ f, file: /bun-version-file:\s*\.bun-version/.test(text) }).toEqual({ f, file: true })
    }
  })

  it('package.json names the same Bun, and the lockfile is committed', () => {
    expect(JSON.parse(read('package.json')).packageManager).toBe(`bun@${PIN}`)
    expect(existsSync(join(ROOT, 'bun.lock'))).toBe(true)
    expect(read('.gitignore').split(/\r?\n/)).not.toContain('bun.lock')
  })

  // A warning, not a failure: a developer's machine is theirs. CI and the image are what is enforced.
  it('says so when the Bun running these tests is another release', () => {
    if (Bun.version !== PIN) console.warn(`⚠ Running Bun ${Bun.version}; the repository pins ${PIN} (.bun-version).`)
    expect(true).toBe(true)
  })
})
