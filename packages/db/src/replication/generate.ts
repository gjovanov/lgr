/**
 * Builds `meta.generated.ts` from the models' own `replicate()` decisions (FR-20.62, plan step
 * P3-1a). Shared by `scripts/gen-replication-meta.ts`, which writes the file, and
 * `unit/replication-meta.test.ts`, which fails when the committed file is not what this produces.
 */
import { REPLICATION_OPTION, STRUCTURAL_PATHS, ownerOf, type ReplicationClass, type ReplicationDecl } from './declare.js'

interface ModelLike {
  modelName: string
  collection: { collectionName: string }
  schema: { get: (key: string) => unknown; eachPath: (fn: (path: string, type: any) => void) => void }
}

export interface MetaEntry {
  collection: string
  class: ReplicationClass
  /**
   * Where a document's org is: `orgId`, or `_id` for `Org` itself. `null`: it has none, and a
   * document with no org is never journaled (FR-20.62).
   */
  orgPath: 'orgId' | '_id' | null
  home?: string[]
  global?: string[]
  node?: string[]
}

/** Every leaf path of a schema, through nested and array subdocuments. */
export function leafPaths(schema: ModelLike['schema'], prefix = ''): string[] {
  const out: string[] = []
  schema.eachPath((p, t) => {
    const full = prefix ? `${prefix}.${p}` : p
    if (t?.schema && (t.instance === 'Array' || t.$isSingleNested || t.instance === 'Embedded' || t.$isMongooseDocumentArray)) {
      out.push(...leafPaths(t.schema, full))
    } else {
      out.push(full)
    }
  })
  return out
}

/** What is wrong with a split declaration: a field with no owner, a path declared twice or for nothing. */
export function splitProblems(name: string, schema: ModelLike['schema'], decl: Extract<ReplicationDecl, { class: 'S' }>): string[] {
  const problems: string[] = []
  const leaves = leafPaths(schema).filter(p => !STRUCTURAL_PATHS.has(p) && !STRUCTURAL_PATHS.has(p.split('.').pop()!))
  const declared = [...decl.home, ...decl.global, ...decl.node]
  for (const p of declared) {
    if (declared.filter(q => q === p).length > 1) problems.push(`${name}: ${p} is declared more than once`)
    if (!leaves.some(l => l === p || l.startsWith(`${p}.`))) problems.push(`${name}: ${p} names no field of the schema`)
  }
  for (const l of leaves) {
    if (!ownerOf(decl, l)) problems.push(`${name}: ${l} has no owner`)
  }
  return [...new Set(problems)]
}

/** The metadata of every model, in name order. Throws for a model that made no decision. */
export function replicationMeta(models: ModelLike[]): Record<string, MetaEntry> {
  const out: Record<string, MetaEntry> = {}
  const undecided: string[] = []
  const problems: string[] = []
  for (const m of [...models].sort((a, b) => a.modelName.localeCompare(b.modelName))) {
    const decl = m.schema.get(REPLICATION_OPTION) as ReplicationDecl | undefined
    if (!decl || !['R', 'S', 'N', 'G'].includes(decl.class)) {
      undecided.push(m.modelName)
      continue
    }
    const orgPath = decl.orgPath ?? (leafPaths(m.schema).includes('orgId') ? 'orgId' : null)
    const entry: MetaEntry = { collection: m.collection.collectionName, class: decl.class, orgPath }
    if (decl.class === 'S') {
      problems.push(...splitProblems(m.modelName, m.schema, decl))
      entry.home = [...decl.home].sort()
      entry.global = [...decl.global].sort()
      entry.node = [...decl.node].sort()
    }
    out[m.modelName] = entry
  }
  if (undecided.length) {
    throw new Error(`these models do not say whether they replicate (replicate(schema, { class })): ${undecided.join(', ')}`)
  }
  if (problems.length) throw new Error(`split models with fields owned by no one or by many:\n  ${problems.join('\n  ')}`)
  return out
}

/** The file `gen:replication-meta` writes. */
export function renderMeta(meta: Record<string, MetaEntry>): string {
  const lines = [
    '// GENERATED by `bun run gen:replication-meta` (packages/db/src/replication/generate.ts) from',
    '// every model\'s `replicate()` decision. Do not edit: change the model, run the script, commit both.',
    '// `unit/replication-meta.test.ts` fails the build when this file is not what the models say.',
    "import type { MetaEntry } from './generate.js'",
    '',
    'export const REPLICATION_META: Readonly<Record<string, Readonly<MetaEntry>>> = {',
  ]
  for (const [name, e] of Object.entries(meta)) {
    const lists = e.class === 'S' ? `, home: ${JSON.stringify(e.home)}, global: ${JSON.stringify(e.global)}, node: ${JSON.stringify(e.node)}` : ''
    lines.push(`  ${name}: { collection: ${JSON.stringify(e.collection)}, class: '${e.class}', orgPath: ${JSON.stringify(e.orgPath)}${lists} },`)
  }
  lines.push('}', '')
  return lines.join('\n').replace(/"/g, "'")
}
