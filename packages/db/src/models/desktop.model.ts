import { Schema, model, type Document, type Types } from 'mongoose'
import { tenantPlugin } from '../plugins/tenant.plugin.js'
import { replicate } from '../replication/declare.js'

/**
 * A registered LGR Desktop: one installation of the desktop client, belonging to one org
 * (FR-14.18).
 *
 * ## Why the entity is `Desktop` and not `Device`
 *
 * ⚠ "Device" already means **fiscal device** throughout the POS and fiscal code — `deviceId`,
 * `deviceNumber`, `getFiscalContext()`, `POSSession.fiscalDeviceId`. The native fiscal bridge is
 * exactly where the two meet (a desktop *bridges* a device), so a shared name would be ambiguous
 * in the one place ambiguity costs the most.
 *
 * ## The row IS the revocation list
 *
 * Every desktop-authenticated request re-reads this row, so revoking a desktop takes effect on its
 * next request whatever its access token's remaining life. That is the whole reason access tokens
 * can be short and stateless while revocation is still immediate.
 */
export interface IDesktop extends Document {
  _id: Types.ObjectId
  orgId: Types.ObjectId

  // ── Identity ──────────────────────────────────────────────────────────────────────────────
  name: string
  /**
   * An admin renamed it, so the desktop's own reported name must not win any more — including
   * across re-enrollment (FR-14.22).
   */
  nameAdminSet: boolean
  /**
   * SHA-256 of hostname + OS + arch. ⚠ For DISPLAY ONLY, never a credential: every machine of a
   * given model and OS build produces the same value, so it identifies a *kind* of machine, not
   * one machine.
   */
  machineId: string
  /** Random 128-bit, generated by the desktop once and kept in non-roaming OS storage. */
  installationId: string
  os: { platform: string; version: string; arch: string }
  hostname: string

  // ── Credential ────────────────────────────────────────────────────────────────────────────
  /**
   * The desktop's Ed25519 PUBLIC key, base64 SPKI DER (60 chars for Ed25519). The private half
   * never leaves the machine's OS keystore, so this row is not sensitive.
   */
  publicKey: string
  /**
   * Bumped by a key rotation. It is a claim in every access token, so bumping it invalidates
   * every token already issued without keeping a token blacklist.
   */
  keyEpoch: number
  keyRotatedAt?: Date

  // ── Lifecycle ─────────────────────────────────────────────────────────────────────────────
  status: 'active' | 'revoked'
  /** Registered with a reusable key for a throwaway VM (FR-14.38); reaped, not kept. */
  ephemeral: boolean
  ephemeralTtlSec?: number
  enrollKeyId?: Types.ObjectId
  enrolledBy?: Types.ObjectId
  enrolledAt: Date
  revokedAt?: Date
  revokedBy?: Types.ObjectId
  revokeReason?: string

  // ── What the desktop reports about itself ─────────────────────────────────────────────────
  appVersion?: string
  capabilities?: { fiscalBridge?: boolean; serialPorts?: string[] }
  lastSeenAt?: Date
  lastPresence?: { ip?: string; clockSkewMs?: number }

  // ── What an admin assigns to it ───────────────────────────────────────────────────────────
  /** Which fiscal devices this desktop may bridge (FR-14.26). */
  fiscalDeviceIds: Types.ObjectId[]
  /** Where "Open LGR" lands, e.g. `/invoicing/cash-sales/new` for a till (FR-14.16). */
  startPath?: string

  createdAt: Date
  updatedAt: Date
}

const desktopSchema = new Schema<IDesktop>(
  {
    name: { type: String, required: true },
    nameAdminSet: { type: Boolean, default: false },
    machineId: { type: String, required: true },
    installationId: { type: String, required: true },
    os: {
      platform: { type: String, default: '' },
      version: { type: String, default: '' },
      arch: { type: String, default: '' },
    },
    hostname: { type: String, default: '' },

    publicKey: { type: String, required: true },
    keyEpoch: { type: Number, default: 1 },
    keyRotatedAt: Date,

    status: { type: String, enum: ['active', 'revoked'], default: 'active' },
    ephemeral: { type: Boolean, default: false },
    ephemeralTtlSec: Number,
    enrollKeyId: { type: Schema.Types.ObjectId, ref: 'DesktopEnrollmentKey' },
    enrolledBy: { type: Schema.Types.ObjectId, ref: 'User' },
    enrolledAt: { type: Date, default: Date.now },
    revokedAt: Date,
    revokedBy: { type: Schema.Types.ObjectId, ref: 'User' },
    revokeReason: String,

    appVersion: String,
    capabilities: {
      fiscalBridge: { type: Boolean, default: false },
      serialPorts: { type: [String], default: undefined },
    },
    lastSeenAt: Date,
    lastPresence: {
      ip: String,
      clockSkewMs: Number,
    },

    fiscalDeviceIds: { type: [{ type: Schema.Types.ObjectId, ref: 'FiscalDevice' }], default: [] },
    startPath: String,
  },
  { timestamps: true },
)

desktopSchema.plugin(tenantPlugin)

/**
 * One ACTIVE registration per installation, per org.
 *
 * ⚠ Partial, so a revoked row does not block re-enrollment of the same machine — which must
 * revive that row rather than create a second one, keeping its assignment and its audit history
 * (FR-14.19).
 *
 * ⚠ A `partialFilterExpression` cannot use `$ne`, hence `$in: ['active']`. Writing the obvious
 * `{ status: { $ne: 'revoked' } }` makes `createIndexes` fail with a message about unsupported
 * operators, and the index is then simply absent.
 */
desktopSchema.index(
  { orgId: 1, installationId: 1 },
  { unique: true, partialFilterExpression: { status: { $in: ['active'] } } },
)
desktopSchema.index({ orgId: 1, status: 1 })
desktopSchema.index({ orgId: 1, lastSeenAt: 1 })
/** The reaper's query: ephemeral rows that have not been seen lately, across all orgs. */
desktopSchema.index({ ephemeral: 1, lastSeenAt: 1 })

replicate(desktopSchema, {
  class: 'S',
  // The registry moves with the org, so a till keeps its id; its presence is the node's it talks to.
  home: ['name', 'nameAdminSet', 'machineId', 'installationId', 'os', 'hostname', 'publicKey', 'keyEpoch', 'keyRotatedAt', 'status', 'ephemeral', 'ephemeralTtlSec', 'enrollKeyId', 'enrolledBy', 'enrolledAt', 'revokedAt', 'revokedBy', 'revokeReason', 'appVersion', 'capabilities', 'fiscalDeviceIds', 'startPath', 'createdAt', 'updatedAt'],
  global: [],
  node: ['lastSeenAt', 'lastPresence'],
})

export const Desktop = model<IDesktop>('Desktop', desktopSchema)
